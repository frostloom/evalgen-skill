#!/usr/bin/env python3
"""Scaffold an evaluation adapter for a business agent.

The adapter implements the EvalGen envelope so EvalScope can drive an agent
whose chat API and state storage do not match ``/v1/eval/chat`` + ``sqlite``:

    GET  /health
    POST /v1/eval/chat   {session_id, message} -> {reply, steps, state, usage}
    GET  /v1/eval/state?session_id=<id>        -> read-only end state
    POST /v1/eval/reset?session_id=<id>        -> per-task reset

The scaffold never assumes a storage engine. It reads the report produced by
``detect_state_source.py`` and generates only the parts that are knowable:

* a working chat proxy, configured from the agent's real request/response shape;
* ``/health`` and a per-session ``/v1/eval/reset`` that calls a reset hook;
* a ``StateSource`` seam with ``read(session_id)`` and ``reset(session_id)``, left
  as ``NotImplementedError`` with the detected engine and tables named in the
  comment. Filling those two methods is the adapter author's job, because only
  they can see the real schema.

Usage:
    python scripts/scaffold_adapter.py \
      --state artifacts/state.json \
      --out <run-dir>/adapter \
      --agent-url http://127.0.0.1:9105 \
      --chat-path /chat \
      --request-field question --request-session-field session_id \
      --response-reply-field answer

When the agent wraps its payload in an envelope (``state``, ``data``,
``result``), pass ``--response-root-field`` so the reply and steps are read from
inside it. Without that flag the adapter reads the top level and reports a
missing reply field, which is the correct failure — a silently empty reply would
score every task as a wrong answer.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

TEMPLATE = '''#!/usr/bin/env python3
"""Evaluation adapter for {project}.

Generated by ``evalscope-evalgen/scripts/scaffold_adapter.py`` from a read-only
scan. The chat proxy is wired to the real agent; ``StateSource.read`` and
``StateSource.reset`` are intentionally unimplemented — fill them in from the
detected schema below, then run ``check_adapter.py`` to prove they are correct.

Detected state source: {engine}
Detected tables: {tables}
Detected state endpoints: {endpoints}
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Any
from urllib.parse import parse_qs, urlsplit

AGENT_BASE_URL = os.environ.get('AGENT_BASE_URL', {agent_url!r}).rstrip('/')
AGENT_API_KEY = os.environ.get('AGENT_API_KEY', '')
AGENT_TIMEOUT = float(os.environ.get('AGENT_TIMEOUT', '60'))
ADAPTER_PORT = int(os.environ.get('EVAL_ADAPTER_PORT', '9115'))

CHAT_PATH = {chat_path!r}
REQUEST_FIELD = {request_field!r}
REQUEST_SESSION_FIELD = {request_session_field!r}
RESPONSE_ROOT_FIELD = {response_root_field!r}
RESPONSE_REPLY_FIELD = {response_reply_field!r}
RESPONSE_STEPS_FIELD = {response_steps_field!r}
# Fields that commonly name a step. A payload whose steps use none of them is
# reported as an error instead of silently producing zero steps, because a step
# list that is empty by accident makes every `process` criterion meaningless.
STEP_NAME_FIELDS = ('name', 'tool', 'node', 'action', 'step', 'label')


class StateSource:
    """Read-only view of the business end state for one session.

    Detected engine: {engine}
    Detected tables: {tables}

    Implement ``read`` to return a JSON-serialisable dict that the eval-set
    checks can address with ``json_path``. Keep it read-only; never write here.
    """

    def read(self, session_id: str) -> dict[str, Any]:
        raise NotImplementedError(
            'implement StateSource.read for the {engine} state of {project}; '
            'return the fields the checks assert on'
        )

    def reset(self, session_id: str) -> None:
        """Clear only this session's evidence, so tasks do not contaminate each other.

        EvalScope runs end-state checks at judge time, after every task has run,
        so a reset must be scoped to ``session_id`` and must never wipe another
        task's rows.
        """
        raise NotImplementedError(
            'implement StateSource.reset to delete only this session\\'s rows'
        )


STATE = StateSource()


def _agent_chat(session_id: str, message: str) -> dict[str, Any]:
    payload = {{REQUEST_FIELD: message, REQUEST_SESSION_FIELD: session_id}}
    headers = {{'Content-Type': 'application/json'}}
    if AGENT_API_KEY:
        headers['Authorization'] = f'Bearer {{AGENT_API_KEY}}'
    request = urllib.request.Request(
        f'{{AGENT_BASE_URL}}{{CHAT_PATH}}',
        data=json.dumps(payload).encode('utf-8'),
        headers=headers,
        method='POST',
    )
    try:
        with urllib.request.urlopen(request, timeout=AGENT_TIMEOUT) as response:
            return json.loads(response.read().decode('utf-8') or '{{}}')
    except urllib.error.HTTPError as exc:
        body = exc.read().decode('utf-8', errors='replace')
        raise RuntimeError(f'agent returned HTTP {{exc.code}}: {{body[:400]}}') from exc


def _payload(data: dict[str, Any]) -> dict[str, Any]:
    """Return the object that carries the reply, honouring the envelope field."""
    if not RESPONSE_ROOT_FIELD:
        return data
    nested = data.get(RESPONSE_ROOT_FIELD)
    if not isinstance(nested, dict):
        raise RuntimeError(
            f'response root field {{RESPONSE_ROOT_FIELD!r}} is missing or not an object'
        )
    return nested


def _raw_steps(payload: dict[str, Any]) -> list[Any]:
    raw = payload.get(RESPONSE_STEPS_FIELD)
    if raw is None:
        raw = payload.get('steps')
    return raw if isinstance(raw, list) else []


def _steps(payload: dict[str, Any]) -> list[dict[str, Any]]:
    """Map the agent's trace onto EvalScope steps.

    Different agents call these tools, nodes, actions or steps, so the name is
    taken from the first field that is present. An item that carries none of
    them is a shape this adapter does not understand; raising is deliberate,
    because dropping it would report "no steps" for an agent that did work.
    """
    steps = []
    for item in _raw_steps(payload):
        if not isinstance(item, dict):
            continue
        name = next(
            (str(item[field]) for field in STEP_NAME_FIELDS if item.get(field)),
            '',
        )
        if not name:
            raise RuntimeError(
                f'step item has none of {{", ".join(STEP_NAME_FIELDS)}}: '
                f'{{sorted(item)[:8]}}'
            )
        result = item.get('result')
        if result is None and item.get('status') is not None:
            result = {{'status': item.get('status')}}
        steps.append({{
            'type': str(item.get('type') or 'tool'),
            'name': name,
            'arguments': item.get('arguments') or item.get('args') or {{}},
            'result': result,
            'elapsed_ms': item.get('elapsed_ms') or item.get('duration_ms'),
        }})
    return steps


class Handler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:
        parts = urlsplit(self.path)
        if parts.path == '/health':
            self._send({{'status': 'ok'}})
            return
        if parts.path == '/v1/eval/state':
            session_id = (parse_qs(parts.query).get('session_id') or [''])[0]
            if not session_id:
                self._send({{'error': 'session_id is required'}}, status=422)
                return
            try:
                self._send(STATE.read(session_id))
            except NotImplementedError as exc:
                self._send({{'error': str(exc)}}, status=501)
            except Exception as exc:  # noqa: BLE001 - surfaced to the caller
                self._send({{'error': f'{{type(exc).__name__}}: {{exc}}'}}, status=500)
            return
        self._send({{'error': 'not found'}}, status=404)

    def do_POST(self) -> None:
        parts = urlsplit(self.path)
        length = int(self.headers.get('content-length', '0'))
        body = json.loads(self.rfile.read(length) or b'{{}}')
        if parts.path == '/v1/eval/reset':
            session_id = (parse_qs(parts.query).get('session_id') or [''])[0]
            try:
                STATE.reset(session_id)
                self._send({{'reset': True, 'session_id': session_id}})
            except NotImplementedError as exc:
                self._send({{'error': str(exc)}}, status=501)
            except Exception as exc:  # noqa: BLE001
                self._send({{'error': f'{{type(exc).__name__}}: {{exc}}'}}, status=500)
            return
        if parts.path == '/v1/eval/chat':
            session_id = str(body.get('session_id') or '')
            message = str(body.get('message') or '')
            if not session_id or not message:
                self._send({{'error': 'session_id and message are required'}}, status=422)
                return
            try:
                data = _agent_chat(session_id, message)
            except Exception as exc:  # noqa: BLE001 - agent failures are evidence
                self._send({{'error': f'{{type(exc).__name__}}: {{exc}}'}}, status=502)
                return
            try:
                payload = _payload(data)
                reply = payload.get(RESPONSE_REPLY_FIELD)
                if not isinstance(reply, str):
                    raise RuntimeError(
                        f'reply field {{RESPONSE_REPLY_FIELD!r}} missing from the '
                        f'{{"nested" if RESPONSE_ROOT_FIELD else "top-level"}} response; '
                        f'saw {{sorted(payload)[:10]}}'
                    )
                steps = _steps(payload)
            except Exception as exc:  # noqa: BLE001 - a wrong shape must not score as an answer
                self._send({{'error': f'{{type(exc).__name__}}: {{exc}}'}}, status=502)
                return
            self._send({{
                'reply': reply,
                'steps': steps,
                'state': payload,
                'usage': data.get('usage') or {{}},
            }})
            return
        self._send({{'error': 'not found'}}, status=404)

    def _send(self, payload: dict[str, Any], status: int = 200) -> None:
        encoded = json.dumps(payload, ensure_ascii=False, default=str).encode('utf-8')
        self.send_response(status)
        self.send_header('content-type', 'application/json')
        self.send_header('content-length', str(len(encoded)))
        self.end_headers()
        self.wfile.write(encoded)

    def log_message(self, *args) -> None:
        pass


if __name__ == '__main__':
    ThreadingHTTPServer(('127.0.0.1', ADAPTER_PORT), Handler).serve_forever()
'''


def _tables_text(state: dict) -> str:
    tables = state.get('tables')
    if not isinstance(tables, list) or not tables:
        return '(none detected)'
    names = [entry.get('name') for entry in tables if isinstance(entry, dict) and entry.get('name')]
    return ', '.join(names) if names else '(none detected)'


def _endpoints_text(state: dict) -> str:
    endpoints = state.get('state_endpoints')
    if not isinstance(endpoints, list) or not endpoints:
        return '(none detected)'
    return ', '.join(str(item) for item in endpoints)


def render(state: dict, args: argparse.Namespace) -> str:
    return TEMPLATE.format(
        project=args.project,
        engine=state.get('primary_engine') or 'unknown',
        tables=_tables_text(state),
        endpoints=_endpoints_text(state),
        agent_url=args.agent_url,
        chat_path=args.chat_path,
        request_field=args.request_field,
        request_session_field=args.request_session_field,
        response_root_field=args.response_root_field,
        response_reply_field=args.response_reply_field,
        response_steps_field=args.response_steps_field,
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--state', required=True, help='report from detect_state_source.py')
    parser.add_argument('--out', required=True, help='adapter directory to create')
    parser.add_argument('--project', default=None, help='project name used in comments')
    parser.add_argument('--agent-url', default='http://127.0.0.1:9105')
    parser.add_argument('--chat-path', default='/chat')
    parser.add_argument('--request-field', default='message')
    parser.add_argument('--request-session-field', default='session_id')
    parser.add_argument('--response-reply-field', default='reply')
    parser.add_argument('--response-steps-field', default='trace')
    parser.add_argument(
        '--response-root-field',
        default='',
        help='envelope field the reply/steps live under (e.g. "state" or "data"); '
             'leave empty when the agent answers at the top level',
    )
    parser.add_argument(
        '--allow-unknown-engine',
        action='store_true',
        help='scaffold even when the report detected no state source (the user must have '
             'confirmed how the end state is observed)',
    )
    args = parser.parse_args()

    path = Path(args.state)
    if not path.is_file():
        print(f'error: state report not found: {path}')
        return 2
    try:
        state = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, json.JSONDecodeError) as exc:
        print(f'error: could not read state report: {exc}')
        return 2
    if not isinstance(state, dict):
        print('error: state report must be a JSON object')
        return 2

    engine = state.get('primary_engine')
    if not engine and not args.allow_unknown_engine:
        print('error: the scan did not identify a state source, so the adapter would have to '
              'invent one.')
        print('       Widen the scan (more source/docs), or ask the user how the end state can be '
              'observed, then re-run detect_state_source.py.')
        print('       If the user already confirmed it, pass --allow-unknown-engine and implement '
              'StateSource from that answer.')
        return 2

    out = Path(args.out)
    if out.exists() and any(out.iterdir()):
        print(f'error: adapter directory is not empty: {out}')
        return 2
    out.mkdir(parents=True, exist_ok=True)
    project = args.project or out.parent.name or 'business-agent'
    args.project = project

    adapter = out / 'eval_adapter.py'
    adapter.write_text(render(state, args), encoding='utf-8')
    adapter.chmod(0o755)

    (out / 'README.md').write_text(
        f"""# Evaluation adapter for {project}

Generated by `evalscope-evalgen/scripts/scaffold_adapter.py`.

Detected state source: **{state.get('primary_engine') or 'unknown'}**
Detected tables: {_tables_text(state)}
Detected state endpoints: {_endpoints_text(state)}

## What is already done

- `GET /health`
- `POST /v1/eval/chat` — proxies to `{args.agent_url}{args.chat_path}`, reads the
  reply from `{args.response_reply_field}` and maps `{args.response_steps_field}`
  into EvalScope steps.
- `POST /v1/eval/reset?session_id=<id>` — calls `StateSource.reset`.

## What you must implement

`StateSource.read(session_id)` and `StateSource.reset(session_id)`. They raise
`NotImplementedError` on purpose: only you can see the real schema, and a wrong
guess would make every end-state check pass or fail for the wrong reason.

Then prove it:

```bash
python scripts/check_adapter.py --adapter-url http://127.0.0.1:9115 --agent-url {args.agent_url}
```

That runs a real turn, asserts the reply and the state agree, and verifies that
reset clears only this session.
""",
        encoding='utf-8',
    )
    print(f'adapter scaffolded: {adapter}')
    print(f'  detected engine: {state.get("primary_engine") or "unknown"}')
    print(f'  implement StateSource.read/reset, then run check_adapter.py')
    return 0


if __name__ == '__main__':
    sys.exit(main())
